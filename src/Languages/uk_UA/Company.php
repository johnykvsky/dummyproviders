    }

    /**
     * Ukrainian Enterprise Identification Code (ЄДРПОУ)
     *
     * 8 digits with checksum mod 11
     *
     * @see https://uk.wikipedia.org/wiki/%D0%84%D0%94%D0%A0%D0%9F%D0%9E%D0%A3
     */
    public function edrpou(): string
    {
        $digits = [$this->randomizer->getInt(1, 9)];
        for ($i = 1; $i < 7; ++$i) {
            $digits[] = $this->randomizer->getInt(0, 9);
        }

        $weights = [1, 2, 3, 4, 5, 6, 7];
        $sum = 0;
        for ($i = 0; $i < 7; ++$i) {
            $sum += $digits[$i] * $weights[$i];
        }
        $check = $sum % 11;
        if ($check === 10) {
            $weights2 = [3, 4, 5, 6, 7, 8, 9];
            $sum2 = 0;
            for ($i = 0; $i < 7; ++$i) {
                $sum2 += $digits[$i] * $weights2[$i];
            }
            $check = $sum2 % 11;
            if ($check === 10) {
                $check = 0;
            }
        }

        return implode('', $digits) . $check;
    }
